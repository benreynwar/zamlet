import argparse
import json
from pathlib import Path
from typing import Any


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--manifest", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    return parser.parse_args()


def load_metadata(value: str) -> dict[str, Any]:
    metadata = json.loads(value)
    if "clock_period_ns" in metadata:
        metadata["clock_period_ns"] = float(metadata["clock_period_ns"])
    if "target_utilization_percent" in metadata:
        metadata["target_utilization_percent"] = float(
            metadata["target_utilization_percent"]
        )
    return metadata


def format_area(area_um2: float) -> str:
    decimals = 3 if area_um2 < 10_000 else 1
    return f"{area_um2:,.{decimals}f} um^2"


def format_status(
    metrics: dict[str, Any],
    flow_status: dict[str, Any] | None = None,
) -> str:
    if flow_status and flow_status["status"] == "failure":
        return f"Flow failed: {flow_status['failed_step']}"

    issues = []
    setup_slack = metrics["timing__setup__ws"]
    hold_slack = metrics["timing__hold__ws"]
    drc_errors = metrics["route__drc_errors"]
    cap_violations = metrics["design__max_cap_violation__count"]
    slew_violations = metrics["design__max_slew_violation__count"]

    if setup_slack < 0:
        issues.append(f"WNS = {setup_slack:.3f} ns")
    if hold_slack < 0:
        issues.append(f"hold slack = {hold_slack:.3f} ns")
    if drc_errors:
        issues.append(f"{drc_errors} DRC violations")
    if cap_violations:
        issues.append(f"{cap_violations} cap violations")
    if slew_violations:
        issues.append(f"{slew_violations} slew violations")
    return "; ".join(issues) if issues else "PASSED"


def format_analysis_status(analysis: dict[str, Any]) -> str:
    issues = []
    if analysis["timing_ns"]["setup_worst_slack"] < 0:
        issues.append(
            f"WNS = {analysis['timing_ns']['setup_worst_slack']:.3f} ns"
        )
    if analysis["timing_ns"]["hold_worst_slack"] < 0:
        issues.append(
            f"hold slack = {analysis['timing_ns']['hold_worst_slack']:.3f} ns"
        )
    if analysis["routing"]["drc_errors"]:
        issues.append(f"{analysis['routing']['drc_errors']} DRC violations")
    if analysis["electrical"]["max_cap_violations"]:
        issues.append(
            f"{analysis['electrical']['max_cap_violations']} cap violations"
        )
    if analysis["electrical"]["max_slew_violations"]:
        issues.append(
            f"{analysis['electrical']['max_slew_violations']} slew violations"
        )
    return "; ".join(issues) if issues else "PASSED"


def append_table(
    lines: list[str],
    headers: list[str],
    rows: list[list[str]],
) -> None:
    lines.append("| " + " | ".join(headers) + " |")
    lines.append("|" + "|".join(["---"] * len(headers)) + "|")
    lines.extend("| " + " | ".join(row) + " |" for row in rows)
    lines.append("")


def main() -> None:
    args = parse_args()
    manifest = json.loads(args.manifest.read_text())

    area_power = []
    for entry in manifest["area_power_runs"]:
        metadata = load_metadata(entry["metadata"])
        metadata["analysis"] = json.loads(Path(entry["analysis"]).read_text())
        area_power.append(metadata)

    sta = []
    for entry in manifest["sta_runs"]:
        metadata = load_metadata(entry["metadata"])
        state = json.loads(Path(entry["state"]).read_text())
        metadata["metrics"] = state["metrics"]
        metadata["flow_status"] = state.get("flow_status")
        sta.append(metadata)

    lines = [
        "<!-- Generated by //dse/systolic_array_note:results. -->",
        "",
        "# Systolic Array Results",
        "",
        "## Power and Area",
        "",
    ]

    pdk_order = ["asap7sc7p5t", "sky130hd"]
    design_order = {"weight-stationary": 0, "sum-stationary": 1}
    for pdk in pdk_order:
        pdk_runs = [run for run in area_power if run["pdk"] == pdk]
        lines.extend([f"### {pdk_runs[0]['pdk_display']}", ""])
        rows = []
        for run in sorted(
            pdk_runs,
            key=lambda value: (value["n"], design_order[value["design"]]),
        ):
            analysis = run["analysis"]
            rows.append([
                run["design"],
                f"{run['n']}x{run['n']}",
                f"{analysis['clock_period_ns']:g} ns",
                f"{analysis['target_utilization_percent']:g}%",
                format_area(analysis["area_um2"]["instances"]),
                f"{analysis['nominal_power_w']['total'] * 1000:.3f} mW",
                format_analysis_status(analysis),
            ])
        append_table(
            lines,
            [
                "Design",
                "Grid Size",
                "Period",
                "Target Util",
                "Cell Area",
                "Power",
                "Status",
            ],
            rows,
        )

    lines.extend(["## Frequency", ""])
    frequency_runs = [run for run in sta if "frequency" in run["tables"]]
    for n in sorted({run["n"] for run in frequency_runs}):
        lines.extend([f"### {n}x{n}", ""])
        size_runs = [run for run in frequency_runs if run["n"] == n]
        periods = sorted(
            {run["clock_period_ns"] for run in size_runs},
            reverse=True,
        )
        rows = []
        for period in periods:
            by_design = {
                run["design"]: format_status(
                    run["metrics"],
                    run["flow_status"],
                )
                for run in size_runs
                if run["clock_period_ns"] == period
            }
            rows.append([
                f"{period:g} ns",
                by_design["sum-stationary"],
                by_design["weight-stationary"],
            ])
        append_table(
            lines,
            ["Clock Period", "Sum-Stationary", "Weight-Stationary"],
            rows,
        )

    lines.extend(["## Utilization", ""])
    utilization_runs = [run for run in sta if "utilization" in run["tables"]]
    for n in sorted({run["n"] for run in utilization_runs}):
        lines.extend([f"### {n}x{n}", ""])
        size_runs = [run for run in utilization_runs if run["n"] == n]
        target_utilizations = sorted({
            run["target_utilization_percent"]
            for run in size_runs
        })
        rows = []
        for target_utilization in target_utilizations:
            matching = [
                run for run in size_runs
                if run["target_utilization_percent"] == target_utilization
            ]
            final_utilization = sum(
                run["metrics"]["design__instance__utilization"] for run in matching
            ) / len(matching)
            by_design = {
                run["design"]: format_status(
                    run["metrics"],
                    run["flow_status"],
                )
                for run in matching
            }
            rows.append([
                f"{target_utilization:g}%",
                f"{final_utilization * 100:.1f}%",
                by_design["sum-stationary"],
                by_design["weight-stationary"],
            ])
        append_table(
            lines,
            ["Target Util", "Final Util", "Sum-Stationary", "Weight-Stationary"],
            rows,
        )

    args.output.write_text("\n".join(lines))


if __name__ == "__main__":
    main()
